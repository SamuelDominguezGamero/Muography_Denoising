import numpy as np
"""
This file contains the bitmap representations of the letters M, U, O, N in different sizes and stroke styles.
Each bit should be interpreted as a voxel being filled (1) or empty (0) in a 3D grid.
The letters are designed to be recognizable when visualized as 2D slices (e.g., at the middle Z-plane) of a 3D voxel grid.
Avaliable resolutions are:
    8x8
    10x10
    12x12
    14x14
    16x16
"""


# use import bitmaps for using the functions of this script in other files


def get_letter(res_x, res_y, letter, stroke):
    """
    Busca la letra basada en dimensiones específicas de X e Y.
    """
    letter = letter.upper()
    dimensions = (res_x, res_y)
    
    try:
        return BITMAP_DATA[dimensions][stroke][letter]
    except KeyError:
        print(f"Error: No existe plantilla para resolución {res_x}x{res_y} con Stroke {stroke}")
        return None
    


def get_word(word_string, res_x_list, res_y_list, stroke_list, spacing=2):
    """
    Genera una matriz concatenando letras con resoluciones y strokes independientes.
    
    Args:
        word_string (str): Ej: "MUON"
        res_x_list (list o int): Lista de anchos ej: [8, 8, 10, 12]
        res_y_list (list o int): Lista de altos ej: [8, 8, 10, 12]
        stroke_list (list o int): Lista de strokes ej: [1, 1, 2, 3]
        spacing (int): Espaciado entre letras.
    """
    n = len(word_string)

    # Normalización: Si se pasa un int, se convierte en lista repetida para todas las letras
    if isinstance(res_x_list, int): res_x_list = [res_x_list] * n
    if isinstance(res_y_list, int): res_y_list = [res_y_list] * n
    if isinstance(stroke_list, int): stroke_list = [stroke_list] * n

    letters = [] # lista de matrices
    for i, char in enumerate(word_string):
        # Buscamos cada letra con sus parámetros específicos
        img = get_letter(res_x_list[i], res_y_list[i], char, stroke_list[i])
        if img is None:
            return None, None
        letters.append(img)

    # El alto de la matriz total debe ser el máximo de las alturas pedidas
    max_h = max(res_y_list)
    
    # El ancho total es la suma de res_x individuales + los espaciados
    total_w = sum(res_x_list) + spacing * (n - 1)

    # Creamos el lienzo base
    word_matrix = np.zeros((max_h, total_w))
        # n_rows = height, n_cols = width
        # Example: res_x = 8, res_y = 10 -> 10 rows (height) y 8 columns (width)

    current_x = 0
    for i, img in enumerate(letters):
        h, w = img.shape # res_y, res_x de la letra actual
        
        # Calculamos el offset vertical para centrar la letra si es más bajita que max_h
        # (Opcional: puedes poner offset_y = 0 para alinearlas arriba)
        offset_y = (max_h - h) // 2 
        
        # Insertamos la letra
        word_matrix[offset_y : offset_y + h, current_x : current_x + w] = img
        
        # Avanzamos el puntero X: ancho de la letra + espaciado
        current_x += w + spacing

    # Convert from bitmap convention (row 0 at the top) to physical convention
    # used by geometry arrays (y index increasing upwards).
    word_matrix = np.flipud(word_matrix)

    return word_matrix, word_matrix.shape # shape = (ny, nx) = (height, width)


def dimensions_test():
    """
    Recorre el diccionario BITMAP_DATA y verifica que cada matriz 
    tenga las dimensiones (res_y, res_x) correctas.
    """
    print("=== Iniciando Test de Dimensiones de Matrices ===")
    errors = 0
    total_checked = 0

    for res_tuple, strokes in BITMAP_DATA.items():
        expected_x, expected_y = res_tuple  # (X, Y) = (Columnas, Filas)
        
        for stroke_val, letters in strokes.items():
            for char, matrix in letters.items():
                total_checked += 1
                current_shape = matrix.shape
                
                # Verificamos si coincide con la resolución declarada en la clave del diccionario
                if current_shape != (expected_y, expected_x):
                    print(f"[ERROR] {char} {expected_y}x{expected_x} Stroke {stroke_val}")
                    print(f"        -> Shape detectado: {current_shape}")
                    errors += 1
                
    print("------------------------------------------------")
    if errors == 0:
        print(f"TEST PASADO: {total_checked} matrices verificadas sin errores.")
    else:
        print(f"TEST FALLIDO: Se encontraron {errors} errores en {total_checked} matrices.")
    print("================================================")

