def resolve_json_files(json_names, json_base):
    """Resolve JSON filenames to full paths in the geometric_configurations_json folder.
    
    Args:
        json_names: List of JSON filenames (e.g., ['geometry.json', 'test.json'])
        json_base: Path to the geometric_configurations_json folder
        
    Returns:
        List of full paths to JSON files
        
    Raises:
        SystemExit if JSON files not found
    """
    resolved_paths = []
    missing_files = []
    
    for json_name in json_names:
        # If user provided a path, use it; otherwise look in json_base
        if "/" in json_name or "\\" in json_name:
            # User provided a path
            json_path = Path(json_name)
        else:
            # User provided just a filename, look in json_base
            json_path = json_base / json_name
        
        if json_path.exists():
            resolved_paths.append(json_path)
        else:
            missing_files.append((json_name, json_path))
    
    if missing_files:
        error_msg = "[ERROR] JSON file(s) not found:\n"
        for original, full_path in missing_files:
            error_msg += f"  • {original} → searched in {full_path}\n"
        error_msg += f"\n[INFO] JSON folder: {json_base}\n"
        error_msg += f"[INFO] Make sure the files are in that directory"
        sys.exit(error_msg)
    
    return resolved_paths


def extract_metadata_from_json_filename(json_path):
    """Extract metadata from JSON filename to use in output filename."""
    json_file = Path(json_path).stem  # Remove .json extension
    # Remove leading underscores and preserve the full name as metadata
    if json_file.startswith("_"):
        metadata = json_file[1:]
    else:
        metadata = json_file
    return metadata


