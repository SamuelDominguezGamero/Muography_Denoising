# ===========================================================================
# MAIN PROCESSING LOOP
# ===========================================================================
for json_idx, json_path in enumerate(json_files, 1):
    print(f"\n[{json_idx}/{len(json_files)}] Processing: {Path(json_path).name}")
    print("-" * 70)
    
    # Extract metadata from filename
    metadata = extract_metadata_from_json_filename(json_path)
    
    # Load JSON
    try:
        with open(json_path, 'r') as f:
            geometry = json.load(f)
    except json.JSONDecodeError as e:
        print(f"[ERROR] Failed to parse JSON: {e}")
        continue
    
    if "TheVoxels" not in geometry:
        print("[ERROR] JSON missing 'TheVoxels' key")
        continue
    
    voxels = geometry["TheVoxels"]
    print(f"[INFO] Found {len(voxels)} voxels in geometry")
    
    # Calculate tensor dimensions
    world_min = -args.world_size / 2.0
    world_max = +args.world_size / 2.0
    n_voxels = int(args.world_size / args.voxel_size)
    
    if args.verbose:
        print(f"[DEBUG] World bounds: [{world_min:.1f}, {world_max:.1f}] cm")
        print(f"[DEBUG] Tensor shape: {n_voxels}×{n_voxels}×{n_voxels}")
    
    # Create binary tensor
    tensor = np.zeros((n_voxels, n_voxels, n_voxels), dtype=np.uint8)
    filled_voxels = 0
    
    if args.verbose:
        print("[INFO] Processing voxels...")
    
    for i, voxel in enumerate(voxels):
        # Skip air voxels
        if voxel.get("materialVoxel", "air").lower() == "air":
            continue
        
        # Extract voxel position and size (in cm)
        x_center = voxel["xPosVoxel"]
        y_center = voxel["yPosVoxel"]
        z_center = voxel["zPosVoxel"]
        
        x_size = voxel["xSizeVoxel"]
        y_size = voxel["ySizeVoxel"]
        z_size = voxel["zSizeVoxel"]
        
        # Calculate voxel boundaries
        x_min = x_center - x_size / 2.0
        x_max = x_center + x_size / 2.0
        y_min = y_center - y_size / 2.0
        y_max = y_center + y_size / 2.0
        z_min = z_center - z_size / 2.0
        z_max = z_center + z_size / 2.0
        
        # Convert cm positions to tensor indices
        x_idx_min = int(np.floor((x_min - world_min) / args.voxel_size))
        x_idx_max = int(np.ceil((x_max - world_min) / args.voxel_size))
        y_idx_min = int(np.floor((y_min - world_min) / args.voxel_size))
        y_idx_max = int(np.ceil((y_max - world_min) / args.voxel_size))
        z_idx_min = int(np.floor((z_min - world_min) / args.voxel_size))
        z_idx_max = int(np.ceil((z_max - world_min) / args.voxel_size))
        
        # Clamp indices to tensor bounds
        x_idx_min = max(0, min(x_idx_min, n_voxels))
        x_idx_max = max(0, min(x_idx_max, n_voxels))
        y_idx_min = max(0, min(y_idx_min, n_voxels))
        y_idx_max = max(0, min(y_idx_max, n_voxels))
        z_idx_min = max(0, min(z_idx_min, n_voxels))
        z_idx_max = max(0, min(z_idx_max, n_voxels))
        
        # Mark tensor voxels
        tensor[y_idx_min:y_idx_max, x_idx_min:x_idx_max, z_idx_min:z_idx_max] = 1
        filled_voxels += 1
        
        if args.verbose and (i % 100 == 0):
            print(f"  [{i}/{len(voxels)}]")
    
    # Calculate statistics
    total_filled = int(np.sum(tensor))
    occupancy = 100.0 * total_filled / (n_voxels ** 3)
    
    print(f"[INFO] Statistics:")
    print(f"       Material voxels: {filled_voxels}")
    print(f"       Tensor voxels filled: {total_filled}")
    print(f"       Occupancy: {occupancy:.2f}%")
    
    # Generate output filenames
    tensor_3d_path = output_3d_dir / f"tensor_3D_{metadata}.npy"
    tensor_2d_path = output_2d_dir / f"tensor_2D_{metadata}.npy"
    
    # Save tensors
    save_3d_tensor(tensor, tensor_3d_path)
    save_2d_projections(tensor, tensor_2d_path, args.world_size)
    
    # Generate PNG visualization in local environment
    if environment == "local":
        visualize_2d_local(tensor, metadata, output_2d_dir, args.world_size)
    
    # Interactive visualizations (if flags are enabled)
    # Load from saved .npy files to visualize exactly what was saved
    if args.visualize_2d:
        print("\n[INFO] Loading saved 2D tensor and displaying...")
        tensor_2d_loaded = np.load(tensor_2d_path)
        visualize_2d_interactive(tensor_2d_loaded)
    
    if args.visualize_3d:
        print("\n[INFO] Loading saved 3D tensor and displaying...")
        tensor_3d_loaded = np.load(tensor_3d_path)
        visualize_3d_interactive(tensor_3d_loaded, args.world_size, args.voxel_size)
    
    print("[OK] Processing complete for this file")

print("\n" + "=" * 70)
print("[SUCCESS] All geometries processed!")
