"""
Create ground truth binary geometry tensors from Geant4 JSON configuration files.

DESCRIPTION:
    Reads a JSON geometry file (generated by create_geometry.py) and converts it to:
    - 3D binary numpy tensor (128×128×128) for UNET training
    - 2D projections as stacked tensor (128×128×3: XY, XZ, YZ)

    Automatically detects environment (local/cluster) and saves to appropriate folders.

INPUT:
    JSON file with voxel structure from create_geometry.py

OUTPUT (Automatic):
    LOCAL ENVIRONMENT:
        3Dimensions/: tensor_3D_{metadatos}.npy (128×128×128, uint8)
        2Dimensions/: tensor_2D_{metadatos}.npy (128×128×3, uint8)
    
    CLUSTER ENVIRONMENT:
        /gpfs/projects/cms/dominguezs/data/ground_truth_data/3Dimensions/
        /gpfs/projects/cms/dominguezs/data/ground_truth_data/2Dimensions/

USAGE:
    # Automatic detection of environment and output paths
    python3 create_ground_truth_from_json.py --json geometry.json
    
    # Process multiple geometries
    python3 create_ground_truth_from_json.py --json geom1.json geom2.json geom3.json
"""

