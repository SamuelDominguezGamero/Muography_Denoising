def visualize_3d_interactive(tensor_3d, world_size, voxel_size):
    """Display 3D geometry interactively using plotly with fixed voxel sizes.
    
    Args:
        tensor_3d: 3D array with shape (128, 128, 128) containing the geometry
        world_size: Size of the world in cm
        voxel_size: Size of each voxel in cm
    """
    try:
        import plotly.graph_objects as go
    except ImportError:
        print("[WARNING] plotly not installed. Install with: pip install plotly")
        return
    
    # Find all filled voxels
    filled_indices = np.argwhere(tensor_3d == 1)
    
    if len(filled_indices) == 0:
        print("[WARNING] No voxels to visualize")
        return
    
    world_min = -world_size / 2.0
    
    # Downsample for performance if needed
    if len(filled_indices) > 10000:
        # Keep every nth voxel for visualization
        stride = len(filled_indices) // 10000
        filled_indices = filled_indices[::stride]
        print(f"[INFO] Downsampled to {len(filled_indices)} voxels for visualization")
    
    # Convert indices to world coordinates (center of voxel)
    voxel_positions = filled_indices * voxel_size + world_min + voxel_size / 2.0
    
    x_coords = voxel_positions[:, 1]  # X is the 2nd index
    y_coords = voxel_positions[:, 0]  # Y is the 1st index
    z_coords = voxel_positions[:, 2]  # Z is the 3rd index
    
    # Create 3D scatter plot with FIXED voxel sizes
    # Use marker size that's independent of zoom level
    fig = go.Figure(data=[go.Scatter3d(
        x=x_coords,
        y=y_coords,
        z=z_coords,
        mode='markers',
        marker=dict(
            size=4,  # Fixed size in display coordinates
            color=z_coords,  # Color by Z coordinate
            colorscale='Viridis',
            showscale=True,
            colorbar=dict(title="Z (cm)"),
            opacity=0.8,
            line=dict(width=0)  # No edge lines to keep performance
        ),
        text=[f'Voxel: ({x:.1f}, {y:.1f}, {z:.1f}) cm' for x, y, z in 
              zip(x_coords, y_coords, z_coords)],
        hovertemplate='<b>%{text}</b><extra></extra>'
    )])
    
    # Set fixed aspect ratio and equal axis ranges for proportional display
    world_max = -world_min
    
    fig.update_layout(
        title=dict(
            text='3D Ground Truth Geometry (Fixed Voxel Proportions)',
            font=dict(size=16)
        ),
        scene=dict(
            xaxis=dict(
                title='X (cm)',
                range=[world_min, world_max],
                backgroundcolor="rgb(230, 230, 230)",
                gridcolor="white",
                showbackground=True,
                spikecolor="black"
            ),
            yaxis=dict(
                title='Y (cm)',
                range=[world_min, world_max],
                backgroundcolor="rgb(230, 230, 230)",
                gridcolor="white",
                showbackground=True,
                spikecolor="black"
            ),
            zaxis=dict(
                title='Z (cm)',
                range=[world_min, world_max],
                backgroundcolor="rgb(230, 230, 230)",
                gridcolor="white",
                showbackground=True,
                spikecolor="black"
            ),
            # CRITICAL: Set aspectratio to 1:1:1 for fixed voxel proportions
            aspectratio=dict(x=1, y=1, z=1),
            camera=dict(
                eye=dict(x=1.5, y=1.5, z=1.3)
            )
        ),
        width=1000,
        height=900,
        hovermode='closest',
        paper_bgcolor="white",
        plot_bgcolor="white"
    )
    
    print("[INFO] Opening 3D visualization in browser...")
    print("[INFO] You can rotate, zoom, and pan while maintaining fixed voxel proportions")
    fig.show()


